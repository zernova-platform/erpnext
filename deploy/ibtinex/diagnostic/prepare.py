"""Prepare a non-publishing diagnostic overlay of the exact candidate source.

Intended repository path: deploy/ibtinex/diagnostic/prepare.py.
"""
import json
from pathlib import Path
import sys
import tarfile

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import ci

BASE = 'frappe/erpnext@sha256:759726db4c3719d8d89f7a3ecb89540286190d65343f25341c3b6c27201ee229'
BASELINE = '886ab6ae187244e7f1b852393384ab6019d56264'
ALLOWED_APP_CHANGES = {
    'erpnext/desktop_icon/erpnext.json', 'erpnext/hooks.py', 'erpnext/ibtinex_branding.py',
    'erpnext/public/images/ibtinex-logo.svg', 'erpnext/public/images/ibtinex-favicon.svg',
    'erpnext/tests/test_ibtinex_branding.py',
}

def prepare():
    changed = ci.run(['git', 'diff', '--name-only', BASELINE, 'HEAD', '--', 'erpnext'], cwd=ci.ROOT).splitlines()
    if any(path not in ALLOWED_APP_CHANGES and not path.startswith('erpnext/ibtinex_starter/') for path in changed):
        raise RuntimeError('Diagnostic overlay does not support other ERP application changes; use the full source build.')
    build_changes = ci.run(['git', 'diff', '--name-only', BASELINE, 'HEAD', '--',
                            'pyproject.toml', 'package.json', 'yarn.lock', 'banking', 'islands'], cwd=ci.ROOT).strip()
    if build_changes:
        raise RuntimeError('Dependencies or compiled frontend sources changed; use the full source build.')
    ci.prepare()
    source = ci.CONTEXT / 'source'
    source.mkdir()
    # This tar is generated by git archive from the checked-out GITHUB_SHA,
    # not a remote branch download or an untrusted third-party archive.
    with tarfile.open(ci.EVIDENCE / 'erpnext-corresponding-source.tar.gz', 'r:gz') as archive:
        archive.extractall(source, filter='data')
    # Preserve all tracked source files in the overlay, including native tests;
    # the normal build context's convenience excludes are not used here.
    (ci.CONTEXT / '.dockerignore').write_text('**/__pycache__\n**/*.pyc\n')
    inputs = json.loads(ci.STATE.read_text())
    # These values describe the independent full source build, not this base.
    inputs.pop('python_base_image', None)
    inputs.pop('node_version', None)
    inputs['expected_frappe_commit'] = inputs.pop('frappe_commit')
    inputs.update(build_method='diagnostic-source-overlay', diagnostic_only=True,
                  diagnostic_runtime_base=BASE, frappe_commit_verified=False,
                  compiled_assets='unchanged official image assets')
    for path in (ci.STATE, ci.EVIDENCE / 'build-inputs.json', ci.CONTEXT / 'release.json'):
        ci.write_json(path, inputs)

def finalize():
    path = ci.EVIDENCE / 'verification-only.json'
    result = json.loads(path.read_text())
    result.update(status='diagnostic-only-passed', diagnostic_only=True,
                  release_qualification=False, image_published=False)
    ci.write_json(ci.EVIDENCE / 'diagnostic-verification-only.json', result)
    path.unlink()

if __name__ == '__main__':
    {'prepare': prepare, 'finalize': finalize}[sys.argv[1]]()
