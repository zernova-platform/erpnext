def validate_request(expected_site, actual_site, accept_sample_data, flags):
	if accept_sample_data is not True:
		raise ValueError("Explicit accept_sample_data=true is required.")
	if not isinstance(expected_site, str) or not expected_site or expected_site != actual_site:
		raise ValueError("expected_site must exactly match the connected Frappe site.")
	if any(flags.get(key) not in (1, True) for key in REQUIRED_SITE_FLAGS):
		raise ValueError("The designated demo site must enable ibtinex_starter_demo, mute_emails and pause_scheduler.")


def seed_date(value=None):
	if value is None:
		return date.today().isoformat()
	if not isinstance(value, str):
		raise ValueError("as_of_date must be an ISO date string.")
	parsed = date.fromisoformat(value)
	if parsed.isoformat() != value or not 2020 <= parsed.year <= 2100:
		raise ValueError("as_of_date must use YYYY-MM-DD within 2020–2100.")
	return value


def coverage_manifest(records):
	result = []
	for module, (kind, keys, note) in MODULE_COVERAGE.items():
		missing = [key for key in keys if key not in records]
		if missing:
			raise ValueError(f"Missing coverage records for {module}: {', '.join(missing)}")
		result.append({"module": module, "kind": kind, "records": list(keys), "note": note})
	return result


def matches_notification_template(actual, expected, fields, child_fields):
	"""Compare all native notification fields, excluding database bookkeeping.

	The framework installs two customizable (is_standard=0), disabled templates.
	Names alone do not prove that a row is still the harmless upstream template.
	"""
	layout = {"Section Break", "Column Break", "Tab Break", "HTML", "Button", "Fold", "Heading"}
	def project(row, schema):
		values = {}
		for field in schema:
			kind, key = field.get("fieldtype"), field.get("fieldname")
			if kind in layout:
				continue
			value = row.get(key)
			if kind in ("Table", "Table MultiSelect"):
				value = [project(child, child_fields[field.get("options")]) for child in (value or [])]
			elif value in (None, "", 0, False):
				value = ""  # Native defaults represent empty/unchecked fields as None or 0.
			values[key] = value
		return values
	return actual.get("name") == expected.get("name") and project(actual, fields) == project(expected, fields)
